#!/usr/bin/env node
// `/docs/**`・`/patterns/**`・`/showcase` の各ルートに、素通しの `layout.tsx` を置く。
//
// なぜ layout が要るか: これらのページは本体が `"use client"` で、クライアント側の
// 部品からは `metadata` も構造化データ（JSON-LD）も出せない。ルートごとに サーバー側の
// layout を挟めば、ページ本体を触らずに題・説明文・canonical と JSON-LD を出せる
// （描画は素通しなので変わらない＝`<script type="application/ld+json">` は表示されない）。
//
//   node scripts/build-seo-layouts.mjs [--check]
//
// 既に自前の layout があるルート（/docs・/patterns・/showcase）は触らない＝
// そこは手で metadata を出す。
import { existsSync, readFileSync, writeFileSync, unlinkSync } from "node:fs";
import { basename, join, relative } from "node:path";
import {
    ROOT,
    hasChildRoutes,
    isRouteGroup,
    listMetadataRoutes,
    listSeoDirs,
} from "./seo-routes.mjs";

const MARKER = "// Generated by `npm run design:sync:seo-layouts`. Do not edit manually.";
const check = process.argv.includes("--check");

function template(path) {
    return `${MARKER}
import type { ReactNode } from "react";
import type { Metadata } from "next";
import { pageMetadata } from "@/lib/seo/page-metadata";
import { StructuredData } from "@/components/seo/StructuredData";

export const metadata: Metadata = pageMetadata(${JSON.stringify(path)});

export default function SeoLayout({ children }: { children: ReactNode }) {
    return (
        <>
            <StructuredData path=${JSON.stringify(path)} />
            {children}
        </>
    );
}
`;
}

function isManaged(file) {
    return existsSync(file) && readFileSync(file, "utf8").startsWith(MARKER);
}

const routes = listMetadataRoutes();
const written = [];
const skipped = [];
const stale = [];
const needsGroup = [];

for (const route of routes) {
    // 子ページを持つルートは、その layout が子も囲む＝そこから JSON-LD を
    // 出すと子のページにも索引の node が付く。索引のページを `(index)` の
    // ルートグループ（URL には出ない）へ移して、そこから出す。
    if (!isRouteGroup(basename(route.dir)) && hasChildRoutes(route, routes)) {
        needsGroup.push(route.path);
        continue;
    }
    const file = join(route.dir, "layout.tsx");
    if (existsSync(file) && !isManaged(file)) {
        skipped.push(route.path);
        continue;
    }
    const next = template(route.path);
    if (existsSync(file) && readFileSync(file, "utf8") === next) continue;
    if (check) {
        written.push(route.path);
        continue;
    }
    writeFileSync(file, next);
    written.push(route.path);
}

// ルートでなくなったところに残った生成物を片づける（転送だけになったページ、
// 消えたページ、`(index)` へ移したあとの親ディレクトリ）。
const keep = new Set(routes.map((route) => route.dir));
for (const dir of listSeoDirs()) {
    if (keep.has(dir)) continue;
    const file = join(dir, "layout.tsx");
    if (!isManaged(file)) continue;
    stale.push(relative(ROOT, file));
    if (!check) unlinkSync(file);
}

const label = check ? "差分" : "書き出し";
console.log(`[seo-layouts] 対象 ${routes.length} 件 / ${label} ${written.length} 件`);
if (stale.length > 0) console.log(`[seo-layouts] 余分な生成物 ${stale.length} 件: ${stale.join(", ")}`);
if (skipped.length > 0) {
    console.log(`[seo-layouts] 自前の layout があるので触らなかったルート: ${skipped.join(", ")}`);
}
if (needsGroup.length > 0) {
    console.error(
        `[seo-layouts] 子ページを持つルートの索引が (index) に入っていません: ${needsGroup.join(", ")}`
    );
    console.error(
        "[seo-layouts] `app/<route>/page.tsx` を `app/<route>/(index)/page.tsx` へ移してから、もう一度実行してください。"
    );
    process.exitCode = 1;
}
if (check && (written.length > 0 || stale.length > 0)) {
    console.error("[seo-layouts] 生成物が古いです。`npm run design:sync:seo-layouts` を実行してください。");
    process.exitCode = 1;
}
if (!check) {
    for (const path of written.slice(0, 5)) {
        console.log(`  ${relative(ROOT, join(routes.find((r) => r.path === path).dir, "layout.tsx"))}`);
    }
}
