import { join } from "node:path";
import { ROOT, writeText } from "./shared.mjs";
import {
  DENSITY_TOKENS,
  FONT_STACKS,
  LEADING_STEPS,
  SPACING_STEPS,
  TEXT_STEPS,
  WEIGHT_STEPS,
  spacingPx,
  spacingValue,
  textPx,
  textValue,
} from "./token-scales.mjs";

// Generates app/lib/data/token-scales.generated.ts — the spacing / type scale
// for /docs/spacing and /docs/typography. Both pages used to carry the scale as
// hand-typed arrays (28 spacing steps, 11 sizes, 5 weights), so the docs were
// themselves a copy of Tailwind's numbers with nothing checking them. Same
// pattern as sync-token-values.mjs: one generated table, imported by the pages.
// Source of truth is token-scales.mjs, which design-verify-scale-tokens.mjs
// holds to the installed Tailwind theme. (#969)

function tsString(value) {
  return JSON.stringify(value);
}

/**
 * The Tailwind width utility that draws a spacing step in the docs ruler.
 * Emitted as a literal so Tailwind's content scan still sees every class.
 */
function widthClass(entry) {
  return `w-${entry.step}`;
}

function rows(entries, toFields) {
  return entries
    .map((entry) => {
      const fields = Object.entries(toFields(entry))
        .map(([key, value]) => `${key}: ${tsString(value)}`)
        .join(", ");
      return `    { ${fields} },`;
    })
    .join("\n");
}

export function buildTokenScalesTs() {
  return `// AUTO-GENERATED by scripts/design-sync/sync-token-scales.mjs — do not edit.
// The spacing / type scale GunjoUI publishes, from scripts/design-sync/token-scales.mjs.
// /docs/spacing and /docs/typography read these instead of re-typing the numbers,
// and public/tokens.css ships the same scale as --space-* / --text-* for npm-less
// adopters. design:verify checks the scale against the installed Tailwind theme. (#969)

export type SpacingStep = {
    /** Tailwind step name, e.g. "4" or "0.5" or "px". */
    step: string;
    /** Standalone-sheet custom property, e.g. "--space-4". */
    token: string;
    /** Shipped value, e.g. "1rem". */
    value: string;
    /** What it measures at the 16px root default, e.g. "16px". */
    px: string;
    /** Tailwind width utility that draws this step. */
    widthClass: string;
};

export type TextStep = {
    utility: string;
    token: string;
    value: string;
    px: string;
};

export type ScaleStep = {
    utility: string;
    token: string;
    value: string;
};

export type FontStack = {
    token: string;
    value: string;
};

export type DensityToken = {
    token: string;
    value: string;
};

export const SPACING_SCALE: SpacingStep[] = [
${rows(SPACING_STEPS, (entry) => ({
  step: entry.step,
  token: entry.name,
  value: spacingValue(entry),
  px: spacingPx(entry),
  widthClass: widthClass(entry),
}))}
];

export const TEXT_SCALE: TextStep[] = [
${rows(TEXT_STEPS, (entry) => ({
  utility: entry.utility,
  token: entry.name,
  value: textValue(entry),
  px: textPx(entry),
}))}
];

export const LEADING_SCALE: ScaleStep[] = [
${rows(LEADING_STEPS, (entry) => ({
  utility: entry.utility,
  token: entry.name,
  value: entry.value,
}))}
];

export const WEIGHT_SCALE: ScaleStep[] = [
${rows(WEIGHT_STEPS, (entry) => ({
  utility: entry.utility,
  token: entry.name,
  value: entry.value,
}))}
];

export const FONT_STACKS: FontStack[] = [
${rows(FONT_STACKS, (entry) => ({ token: entry.name, value: entry.value }))}
];

export const DENSITY_TOKENS: DensityToken[] = [
${rows(DENSITY_TOKENS, (entry) => ({ token: entry.name, value: entry.value }))}
];
`;
}

export function syncTokenScales({ root = ROOT } = {}) {
  const outputPath = join(root, "app", "lib", "data", "token-scales.generated.ts");
  writeText(outputPath, buildTokenScalesTs());
  console.log(
    "design:sync: Updated app/lib/data/token-scales.generated.ts from scripts/design-sync/token-scales.mjs"
  );
}
