#!/usr/bin/env node
// 元データ（SSOT）から題か説明文が引けないページの分だけ、ページ自身の
// 見出し（h1）と導入文（h1 直後の段落）を本番ビルドから読み取って
// `app/lib/seo/page-copy.generated.json` に書き出す。
//
// ⛔ 文言を作らない＝ページに出ている文字だけを写す。引けなかったページは
// 一覧で報告して、JSON には入れない（検査がそこで落ちる）。
//
//   npx next build && npx next start -p 13131
//   node scripts/build-seo-page-copy.mjs --base-url=http://127.0.0.1:13131
//
// 題・説明文の大半（部品 251 ページ・パターン・ショーケース）は
// app/lib/seo/curated-copy.ts が元データから直接組み立てるので、ここには出ない。
import { writeFileSync } from "node:fs";
import { join } from "node:path";
import { ROOT, listMetadataRoutes, loadTsModule } from "./seo-routes.mjs";

const OUTPUT = join(ROOT, "app", "lib", "seo", "page-copy.generated.json");

const baseUrlArg = process.argv.find((arg) => arg.startsWith("--base-url="));
const BASE_URL = (baseUrlArg ? baseUrlArg.slice("--base-url=".length) : "http://127.0.0.1:13131").replace(/\/$/, "");

function stripTags(html) {
    return html
        .replace(/<[^>]+>/g, "")
        .replace(/&amp;/g, "&")
        .replace(/&lt;/g, "<")
        .replace(/&gt;/g, ">")
        .replace(/&quot;/g, '"')
        .replace(/&#x27;|&#39;/g, "'")
        .replace(/\s+/g, " ")
        .trim();
}

/**
 * ページの題。ふつうは最初の h1。ただし h1 が文（「。」や「.」で終わる）の
 * ときは題にならないので、その上の小見出し（`<header>` の中の札）を使う。
 */
function extractHeading(html) {
    const match = html.match(/<h1[^>]*>([\s\S]*?)<\/h1>/i);
    if (!match) return null;
    const heading = stripTags(match[1]);
    if (!/[。.]$/.test(heading)) return heading;
    const before = html.slice(0, match.index);
    const headerStart = before.lastIndexOf("<header");
    if (headerStart < 0) return heading;
    const eyebrow = stripTags(before.slice(headerStart));
    return eyebrow.length > 0 && eyebrow.length <= 40 ? eyebrow : heading;
}

/** h1 のあと、次の見出しより前に出る最初の段落＝そのページの導入文。 */
function extractLead(html) {
    const headingEnd = html.search(/<\/h1>/i);
    if (headingEnd < 0) return null;
    const rest = html.slice(headingEnd);
    const paragraph = rest.match(/<p[^>]*>([\s\S]*?)<\/p>/i);
    if (!paragraph) return null;
    const nextHeading = rest.search(/<h[12][\s>]/i);
    if (nextHeading >= 0 && nextHeading < paragraph.index) return null;
    const text = stripTags(paragraph[1]);
    return text.length > 0 ? text : null;
}

const { curatedCopy, clampDescription, TITLE_SUFFIX } = await loadTsModule("app/lib/seo/curated-copy.ts");

const routes = listMetadataRoutes();
const gaps = routes
    .map((route) => ({ route, copy: curatedCopy(route.path) }))
    .filter(({ copy }) => !copy.title || !copy.description);

console.log(`[seo-copy] ページ ${routes.length} 件中、元データで足りないのは ${gaps.length} 件`);

const generated = {};
const unresolved = [];

for (const { route, copy } of gaps) {
    const res = await fetch(`${BASE_URL}${route.path}`, { redirect: "manual" });
    if (res.status !== 200) {
        unresolved.push(`${route.path}（HTTP ${res.status}）`);
        continue;
    }
    const html = await res.text();
    const heading = extractHeading(html);
    const lead = extractLead(html);
    const title = copy.title ?? (heading ? `${heading} ${TITLE_SUFFIX.docs}` : null);
    const description = copy.description ?? (lead ? clampDescription(lead) : null);
    if (!title || !description) {
        unresolved.push(
            `${route.path}（${!title ? "題" : ""}${!title && !description ? "と" : ""}${!description ? "説明文" : ""}が取れない）`
        );
        continue;
    }
    const entry = {};
    if (!copy.title) entry.title = title;
    if (!copy.description) entry.description = description;
    entry.source = [!copy.title ? "page.h1" : null, !copy.description ? "page.lead" : null]
        .filter(Boolean)
        .join("+");
    generated[route.path] = entry;
}

const sorted = Object.fromEntries(Object.keys(generated).sort().map((key) => [key, generated[key]]));
writeFileSync(
    OUTPUT,
    `${JSON.stringify(
        {
            $comment:
                "Generated by `npm run design:sync:seo-copy`. ページ自身の見出し（h1）と導入文から写した題と説明文。手で編集しない。",
            pages: sorted,
        },
        null,
        2
    )}\n`
);

console.log(`[seo-copy] ${Object.keys(sorted).length} 件を ${OUTPUT.replace(ROOT, "")} に書き出しました`);
if (unresolved.length > 0) {
    console.log(`[seo-copy] 取れなかったページ ${unresolved.length} 件:`);
    for (const line of unresolved) console.log(`  - ${line}`);
    process.exitCode = 1;
}
